import { Resend } from 'resend'
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnySupabaseClient = any

const resend = new Resend(process.env.RESEND_API_KEY)
const APP_URL = process.env.NEXT_PUBLIC_APP_URL || 'https://getsuitel.com'

// Shared invite-code generation + email, used by:
//  - POST /api/hq/branches/[id]/invite (HQ admin manually generates/shares a code)
//  - the agreement sign-off flow (auto-fires once a branch's franchise
//    agreement is marked signed, if pending_superadmin_email was set)
// Keeping this in one place means both paths always produce the same code
// format, expiry, and email template — no drift between "generate manually"
// and "generate automatically."

export function generateInviteCode(): string {
  // 8 uppercase alphanumeric chars, no ambiguous O/0/I/1 pairs, formatted XXXX-XXXX
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'
  const buf = new Uint8Array(8)
  crypto.getRandomValues(buf)
  const raw = Array.from(buf).map(b => chars[b % chars.length]).join('')
  return `${raw.slice(0, 4)}-${raw.slice(4)}`
}

