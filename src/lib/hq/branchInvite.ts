/**
 * Generates a fresh invite code for a branch, expires any unused existing
 * codes first, and optionally emails it. Returns the code + url either way
 * so callers can also show/copy it in the UI.
 */
export async function issueBranchInvite(
  supabase: AnySupabaseClient,
  opts: { branchId: string; branchName: string; createdBy: string; email?: string | null },
): Promise<{ code: string; inviteUrl: string; expiresAt: string; emailed: boolean }> {
  const { branchId, branchName, createdBy, email } = opts

  // Expire any existing unused codes for this branch
  await supabase
    .from('invite_codes')
    .update({ expires_at: new Date().toISOString() })
    .eq('branch_id', branchId)
    .is('used_by', null)

  const code = generateInviteCode()
  const expiresAt = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000)

  const { error } = await supabase
    .from('invite_codes')
    .insert({
      code,
      branch_id: branchId,
      created_by: createdBy,
      expires_at: expiresAt.toISOString(),
    })

  if (error) throw new Error(error.message)

  const inviteUrl = `${APP_URL}/auth/invite?code=${code}`
  let emailed = false

  if (email?.trim()) {
    try {
      const expiresDate = expiresAt.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })
      await resend.emails.send({
        from: 'GetSuitel <noreply@getsuitel.com>',
        to: email.trim(),
        subject: `You're invited to manage the ${branchName} branch — GetSuitel`,
        html: inviteEmailHtml(branchName, code, inviteUrl, expiresDate),
      })
      emailed = true
    } catch {
      // Email failure is non-fatal — the code still exists and can be copied/shared manually
    }
  }

  return { code, inviteUrl, expiresAt: expiresAt.toISOString(), emailed }
}
